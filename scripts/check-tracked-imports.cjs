#!/usr/bin/env node
/**
 * Fails when committed code imports a module that is not committed.
 *
 * `tsc` in the working tree cannot see this: it resolves the file on disk, so a
 * module that was never `git add`ed typechecks clean locally and then breaks the
 * deploy build (and CI) for everyone else. This exports HEAD to a throwaway
 * directory — where untracked files do not exist — and typechecks that copy.
 *
 * Usage: node scripts/check-tracked-imports.cjs
 */

const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DIR = path.join(ROOT, ".import-check");

function run() {
  fs.rmSync(DIR, { recursive: true, force: true });
  fs.mkdirSync(DIR, { recursive: true });

  const tarPath = path.join(DIR, "head.tar");
  fs.writeFileSync(tarPath, execFileSync("git", ["archive", "--format=tar", "HEAD"], {
    cwd: ROOT,
    maxBuffer: 256 * 1024 * 1024,
  }));
  // Relative paths inside DIR: GNU/bsdtar on Windows read "C:..." as a remote
  // host, so never pass the absolute path here.
  execFileSync("tar", ["-xf", "head.tar"], { cwd: DIR });
  fs.rmSync(tarPath);

  // Generated by Next and safe to regenerate; tsconfig includes it.
  const envTypes = path.join(ROOT, "next-env.d.ts");
  if (fs.existsSync(envTypes)) fs.copyFileSync(envTypes, path.join(DIR, "next-env.d.ts"));

  const tsc = path.join(
    ROOT,
    "node_modules",
    ".bin",
    process.platform === "win32" ? "tsc.cmd" : "tsc"
  );

  let output = "";
  try {
    execFileSync(tsc, ["--noEmit", "-p", "tsconfig.json"], {
      cwd: DIR,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 300_000,
    });
  } catch (err) {
    output = `${err.stdout || ""}${err.stderr || ""}`;
  }

  const missing = output
    .split("\n")
    .filter((line) => /error TS2307: Cannot find module/.test(line));

  if (missing.length > 0) {
    console.error(
      `Committed code imports ${missing.length} module(s) that are not in the repository.\n` +
        "Add the file(s) to git — a working-tree build would hide this.\n"
    );
    console.error(missing.join("\n"));
    return 1;
  }

  // Any other type error is a real build break; surface it rather than pass.
  if (/error TS\d+/.test(output)) {
    console.error(output.split("\n").filter((l) => /error TS\d+/.test(l)).join("\n"));
    return 1;
  }

  console.log("Every committed import resolves inside HEAD.");
  return 0;
}

let code = 1;
try {
  code = run();
} finally {
  fs.rmSync(DIR, { recursive: true, force: true });
}
process.exit(code);
